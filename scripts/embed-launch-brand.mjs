import { readFileSync, writeFileSync } from "node:fs";

// Keep the pre-hydration lockup independent of network requests and of the
// serverless runtime filesystem. Derive it from the canonical brand artwork.
const inline = (name) =>
  `data:image/svg+xml;base64,${readFileSync(new URL(`../public/assets/${name}`, import.meta.url), "base64")}`;
const output = new URL(
  "../src/components/venue/launch-brand-data.ts",
  import.meta.url,
);
const text = `// Generated by scripts/embed-launch-brand.mjs from public/assets.\nexport const launchBrand = {\n  mark: ${JSON.stringify(inline("papupay-mark.svg"))},\n  wordmark: ${JSON.stringify(inline("papupay-wordmark.svg"))},\n} as const;\n`;
let existing;
try {
  existing = readFileSync(output, "utf8");
} catch {}
if (existing !== text) writeFileSync(output, text);
