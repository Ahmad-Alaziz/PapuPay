CREATE TABLE memberships (
  id TEXT PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  checkout TEXT NOT NULL UNIQUE,
  created_at TEXT NOT NULL
);

CREATE TABLE guest_sessions (
  token_hash TEXT PRIMARY KEY,
  card_id TEXT NOT NULL REFERENCES memberships(id),
  expires_at BIGINT NOT NULL
);

CREATE TABLE staff_sessions (
  token_hash TEXT PRIMARY KEY,
  role TEXT NOT NULL CHECK (role IN ('staff', 'manager')),
  expires_at BIGINT NOT NULL
);

CREATE TABLE ledger (
  id TEXT PRIMARY KEY,
  action_id TEXT NOT NULL UNIQUE,
  card_id TEXT NOT NULL REFERENCES memberships(id),
  kind TEXT NOT NULL CHECK (kind IN ('stamp', 'redeem', 'reverse')),
  receipt TEXT,
  reverses TEXT UNIQUE REFERENCES ledger(id),
  reason TEXT,
  actor TEXT NOT NULL,
  actor_role TEXT NOT NULL,
  created_at TEXT NOT NULL,
  sequence BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE INDEX ledger_card_sequence ON ledger (card_id, sequence DESC);

CREATE TABLE receipt_claims (
  receipt TEXT PRIMARY KEY,
  event_id TEXT NOT NULL REFERENCES ledger(id)
);

CREATE INDEX receipt_claims_event ON receipt_claims (event_id);

CREATE TABLE review_clicks (
  day TEXT PRIMARY KEY,
  clicks BIGINT NOT NULL
);

CREATE TABLE auth_attempts (
  scope TEXT NOT NULL,
  client_hash TEXT NOT NULL,
  attempts INTEGER NOT NULL,
  expires_at BIGINT NOT NULL,
  PRIMARY KEY (scope, client_hash)
);

CREATE INDEX auth_attempts_expiry ON auth_attempts (scope, expires_at);
